package be.abis.exercise.service;

import be.abis.exercise.exception.PersonAlreadyExistsException;
import be.abis.exercise.exception.PersonCanNotBeDeletedException;
import be.abis.exercise.exception.PersonNotFoundException;
import be.abis.exercise.model.Company;
import be.abis.exercise.model.Person;
import be.abis.exercise.repository.CompanyJpaRepository;
import be.abis.exercise.repository.PersonJpaRepository;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.dao.DataAccessException;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.List;

@Service
public class AbisPersonService implements PersonService {

    // BEFORE: @Autowired PersonRepository personRepository;   (CSV file)
    @Autowired
    PersonJpaRepository personRepository;

    @Autowired
    CompanyJpaRepository companyRepository;

    @Override
    public List<Person> getAllPersons() {
        // BEFORE: return personRepository.getAllPersons();
        return personRepository.findAll();
    }

    @Override
    public Person findPerson(int id) throws PersonNotFoundException {
        // BEFORE: return personRepository.findPerson(id);
        return personRepository.findById(id)
                .orElseThrow(() -> new PersonNotFoundException("person with id " + id + " not found"));
    }

    @Override
    public Person findPerson(String emailAddress, String passWord) throws PersonNotFoundException {
        if (emailAddress == null || passWord == null) {
            throw new PersonNotFoundException("email/password incorrect");
        }
        // BEFORE: return personRepository.findPerson(emailAddress, passWord);
        return personRepository.findByEmailAddressIgnoreCaseAndPassword(emailAddress, passWord)
                .orElseThrow(() -> new PersonNotFoundException("email/password incorrect"));
    }

    // BEFORE: public void addPerson(Person p) throws PersonAlreadyExistsException { personRepository.addPerson(p); }
    // NOW: also decides whether the person's company already exists, and returns the saved person
    @Override
    @Transactional
    public Person addPerson(Person p) throws PersonAlreadyExistsException {
        if (personRepository.findByEmailAddressIgnoreCase(p.getEmailAddress()).isPresent()) {
            throw new PersonAlreadyExistsException("you were already registered, login please");
        }
        p.setPersonId(0); // generated by the DB
        Company c = p.getCompany();
        if (c != null) {
            // existing company: link to it; new company: it is persisted together with the person (cascade)
            String town = c.getAddress() != null ? c.getAddress().getTown() : null;
            Company existing = companyRepository.findByNameAndTown(c.getName(), town);
            if (existing != null) {
                p.setCompany(existing);
            } else {
                c.setCompanyNr(0);
            }
        }
        return personRepository.save(p);
    }

    // BEFORE: personRepository.deletePerson(id);
    @Override
    @Transactional(rollbackFor = PersonCanNotBeDeletedException.class)
    public void deletePerson(int id) throws PersonCanNotBeDeletedException {
        Person p = personRepository.findById(id)
                .orElseThrow(() -> new PersonCanNotBeDeletedException("person with id " + id + " does not exist"));
        try {
            personRepository.delete(p);
            personRepository.flush();
        } catch (DataAccessException e) {
            throw new PersonCanNotBeDeletedException("person with id " + id + " could not be removed");
        }
    }

    // BEFORE: public void changePassword(Person p, String newPswd) { personRepository.changePassword(p,newPswd); }
    @Override
    @Transactional
    public Person changePassword(Person p, String newPswd) throws PersonNotFoundException {
        Person existing = findPerson(p.getPersonId());
        existing.setPassword(newPswd);
        return personRepository.save(existing);
    }

    @Override
    public List<Person> findPersonsByCompanyName(String compName) {
        // BEFORE: return personRepository.findPersonsByCompanyName(compName);
        return personRepository.findByCompanyNameIgnoreCase(compName);
    }
}
