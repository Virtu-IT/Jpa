package be.abis.exercise.service;

import be.abis.exercise.exception.CourseNotFoundException;
import be.abis.exercise.model.Course;
import be.abis.exercise.repository.CourseJpaRepository;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.List;

@Service
public class AbisCourseService implements CourseService {

    // BEFORE: @Autowired CourseRepository courseRepository;   (in-memory list)
    @Autowired
    CourseJpaRepository courseRepository;

    @Override
    public List<Course> findAllCourses() {
        // BEFORE: return courseRepository.findAllCourses();
        return courseRepository.findAll();
    }

    @Override
    public Course findCourse(int id) {
        // BEFORE: return courseRepository.findCourse(id);
        return courseRepository.findById(id).orElse(null);
    }

    @Override
    public Course findCourse(String shortTitle) {
        // BEFORE: return courseRepository.findCourse(shortTitle);
        return courseRepository.findByShortTitle(shortTitle);
    }

    // BEFORE: public void addCourse(Course c) { }   (empty, nothing was stored)
    @Override
    @Transactional
    public Course addCourse(Course c) {
        // the id is generated by the DB, so make sure a passed id can never turn this into an update
        c.setCourseId(0);
        return courseRepository.save(c);
    }

    // BEFORE: public void updateCourse(Course c) { }   (empty)
    // NOW: fetch the course first, then change the managed entity and save it
    @Override
    @Transactional
    public Course updateCourse(Course c) {
        Course existing = courseRepository.findById(c.getCourseId())
                .orElseThrow(() -> new CourseNotFoundException("course with id " + c.getCourseId() + " not found"));
        existing.setShortTitle(c.getShortTitle());
        existing.setLongTitle(c.getLongTitle());
        existing.setNumberOfDays(c.getNumberOfDays());
        existing.setPricePerDay(c.getPricePerDay());
        return courseRepository.save(existing);
    }

    // BEFORE: public void deleteCourse(int id) { }   (empty)
    @Override
    @Transactional
    public void deleteCourse(int id) {
        courseRepository.deleteById(id);
    }

    @Override
    public void changePrice(int id, double price) {
        if (courseRepository.changePrice(id, price) == 0) {
            throw new CourseNotFoundException("course with id " + id + " not found");
        }
    }

}
